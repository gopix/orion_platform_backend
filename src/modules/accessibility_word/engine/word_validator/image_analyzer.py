"""Step 3: images and alt text. Static analysis can find missing alt text, not wrong alt text."""
from __future__ import annotations

import re

from src.modules.accessibility_word.engine.word_validator.base_analyzer import BaseAnalyzer, Item


_FILE_NAME = re.compile(r"\.(png|jpe?g|gif|bmp|tiff?|svg|emf|wmf|webp)$", re.IGNORECASE)
_DEFAULT_NAME = re.compile(r"^(picture|image|graphic|photo|figure|chart|diagram|img|dsc|screenshot)"
                           r"[\s_-]*\d*$", re.IGNORECASE)
_AUTO_GENERATED = re.compile(r"(description automatically generated|generated by ai)", re.IGNORECASE)


class ImageAnalyzer(BaseAnalyzer):
    name = "ImageAnalyzer"
    category = "IMAGE_ACCESSIBILITY"

    @staticmethod
    def _described(ctx):
        return [i for i in ctx.images if i.alt and not i.decorative]

    def _is_placeholder(self, image) -> bool:
        alt = image.alt.strip()
        target = (image.target or "").rsplit("/", 1)[-1]
        return bool(_FILE_NAME.search(alt) or _DEFAULT_NAME.match(alt)
                    or alt.lower() == target.lower() or alt == image.name)

    def check_img_001_alt_present(self, ctx, rec):
        if not ctx.images:
            rec.not_applicable("IMG-001", "The document has no images.")
            return
        rec.evaluate("IMG-001", [
            Item(f"The {image.kind} has no alt text", image.location)
            for image in ctx.images if not image.alt and not image.decorative])

    def check_img_002_placeholder_alt(self, ctx, rec):
        described = self._described(ctx)
        if not described:
            rec.not_applicable("IMG-002", "No image has alt text to inspect.")
            return
        rec.evaluate("IMG-002", [
            Item(f'Alt text is a placeholder: "{image.alt}"', image.location)
            for image in described if self._is_placeholder(image)])

    def check_img_003_auto_generated(self, ctx, rec):
        described = self._described(ctx)
        if not described:
            rec.not_applicable("IMG-003", "No image has alt text to inspect.")
            return
        items = [Item("Alt text appears to be auto-generated", image.location)
                 for image in described if _AUTO_GENERATED.search(image.alt)]
        if items:
            rec.manual("IMG-003", items)
        else:
            rec.evaluate("IMG-003", [])

    def check_img_004_alt_accuracy(self, ctx, rec):
        reviewable = [i for i in self._described(ctx) if not self._is_placeholder(i)]
        if not reviewable:
            rec.not_applicable("IMG-004", "No image has meaningful alt text to verify.")
            return
        rec.manual("IMG-004", [
            Item(f'Confirm the alt text is accurate: "{image.alt[:80]}"', image.location)
            for image in reviewable])
