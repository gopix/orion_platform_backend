#!/usr/bin/env python3
"""
alt_apply.py
============
Applies the NEEDS_HUMAN decisions produced by alt_text_sanitizer.py.

alt_text_sanitizer deliberately refuses to invent descriptions for images that
have no printed caption - it tags them "[TO BE DESCRIBED]" and lists them in
--report-json.  This tool consumes a decisions file and closes them out:

    [
      {"page": 2,  "mcid": 29, "alt": "A camel standing on sand in a desert."},
      {"page": 16, "mcid": 22, "decorative": true},
      ...
    ]

  * "alt"        -> the Figure keeps its tag and gets the description
  * "decorative" -> the image is re-marked /Artifact and the Figure element is
                    dropped.  Correct for banner shapes and icons that sit
                    UNDER live text: describing them would make a screen reader
                    announce the same words twice.

The decisions file can be written by a person, or generated by a vision model
(feed it the crop plus the surrounding paragraph).  Either way the PDF surgery
below is the same, and the ParentTree is rebuilt afterwards.

Usage
-----
    python alt_apply.py in.pdf out.pdf decisions.json [--report]
"""
from __future__ import annotations

import json
import sys

import pikepdf
from pikepdf import Dictionary, Name, Array

try:
    from .struct_utils import (rebuild_parent_tree, artifact_mcids,
                               fix_struct_parents, strip_ghost_refs, prune_empty)
except ImportError:
    from struct_utils import (rebuild_parent_tree, artifact_mcids,
                              fix_struct_parents, strip_ghost_refs, prune_empty)


def run(inp, outp, decisions_path, report=False):
    pdf = pikepdf.open(inp)
    pages = list(pdf.pages)
    pidx = {p.obj.objgen: i for i, p in enumerate(pages)}
    decisions = json.load(open(decisions_path, encoding="utf-8"))
    want = {(d["page"] - 1, d["mcid"]): d for d in decisions}

    # locate the Figure that owns each targeted MCID
    found = {}

    def mcids_of(node, cur):
        out = []
        k = node.get("/K")
        items = list(k) if isinstance(k, Array) else ([k] if k is not None else [])
        for it in items:
            if isinstance(it, int):
                out.append((cur, int(it)))
            elif isinstance(it, Dictionary) and it.get("/Type") == Name("/MCR"):
                pg = it.get("/Pg")
                pi = pidx.get(pg.objgen) if pg is not None else cur
                out.append((pi, int(it.get("/MCID"))))
        return out

    def walk(node, cur, parent):
        if isinstance(node, Array):
            for k in node:
                walk(k, cur, parent)
            return
        if not isinstance(node, Dictionary):
            return
        if node.get("/Type") in (Name("/MCR"), Name("/OBJR")):
            return
        pg = node.get("/Pg")
        c = pidx.get(pg.objgen) if pg is not None else cur
        if node.get("/S") == Name("/Figure"):
            for key in mcids_of(node, c):
                if key in want:
                    found[key] = (node, parent)
        walk(node.get("/K"), c, node)

    walk(pdf.Root["/StructTreeRoot"].get("/K"), None, None)

    to_artifact, described, dropped, missing = {}, [], [], []
    for key, d in want.items():
        if key not in found:
            missing.append(key)
            continue
        node, parent = found[key]
        if d.get("decorative"):
            k = parent.get("/K")
            if isinstance(k, Array):
                parent["/K"] = Array([c for c in k
                                      if not (isinstance(c, Dictionary)
                                              and c.objgen == node.objgen)])
            to_artifact.setdefault(key[0], set()).add(key[1])
            to_artifact[key[0]].update(m for _, m in mcids_of(node, key[0]))
            dropped.append(key)
        else:
            node["/Alt"] = pikepdf.String(d["alt"])
            described.append((key, d["alt"]))

    n = 0
    for pi, mcids in to_artifact.items():
        n += artifact_mcids(pdf, pages[pi], mcids)

    strip_ghost_refs(pdf)
    prune_empty(pdf)
    fix_struct_parents(pdf)
    rebuild_parent_tree(pdf)
    pdf.save(outp)
    pdf.close()   # Windows: os.replace() is denied while the file is still open

    if report:
        print(f"described  : {len(described)}")
        for (p, m), a in described:
            print(f"    p{p+1:<3} mcid={m:<4} {a!r}")
        print(f"decorative -> Artifact : {len(dropped)} figures, {n} MC re-marked")
        if missing:
            print(f"NOT FOUND (stale decisions file): {missing}")
    print(f"saved {outp}")


if __name__ == "__main__":
    a = [x for x in sys.argv[1:] if not x.startswith("--")]
    run(a[0], a[1], a[2], report="--report" in sys.argv)
